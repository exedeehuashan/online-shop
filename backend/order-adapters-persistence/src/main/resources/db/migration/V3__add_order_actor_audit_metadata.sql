CREATE TABLE order_audit_events (
  internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL CONSTRAINT ux_order_audit_event_id UNIQUE,
  order_internal_id BIGINT NULL,
  order_public_id UUID NULL,
  actor_id UUID NOT NULL,
  action VARCHAR(64) NOT NULL CONSTRAINT ck_order_audit_action CHECK
    (action IN ('ORDER_CREATED','ORDER_CONFIRMED','ORDER_CANCELLED','V1_CREATE_FOR_OTHER','V1_MANAGE_FOR_OTHER')),
  occurred_at TIMESTAMPTZ NOT NULL,
  correlation_id VARCHAR(128) NOT NULL,
  outcome VARCHAR(16) NOT NULL CONSTRAINT ck_order_audit_outcome CHECK (outcome = 'SUCCEEDED'),
  reason_code VARCHAR(120) NULL,
  CONSTRAINT ck_order_audit_order_refs CHECK ((order_internal_id IS NULL) = (order_public_id IS NULL)),
  CONSTRAINT fk_order_audit_order FOREIGN KEY(order_internal_id, order_public_id)
    REFERENCES orders(internal_id, public_id) ON DELETE RESTRICT
);
CREATE INDEX ix_order_audit_order_timeline
  ON order_audit_events(order_public_id, occurred_at DESC, internal_id DESC);

CREATE FUNCTION reject_order_audit_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'order audit history is immutable' USING ERRCODE = 'check_violation';
END;
$$;
CREATE TRIGGER trg_order_audit_immutable BEFORE UPDATE OR DELETE ON order_audit_events
FOR EACH ROW EXECUTE FUNCTION reject_order_audit_change();

CREATE OR REPLACE FUNCTION reject_order_snapshot_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(NEW.public_id, NEW.customer_ref, NEW.customer_internal_id, NEW.customer_name_snapshot,
         NEW.currency, NEW.total_amount, NEW.item_count, NEW.recipient, NEW.address_line1, NEW.address_line2,
         NEW.city, NEW.region, NEW.postal_code, NEW.country_code, NEW.phone, NEW.created_at, NEW.created_by)
     IS DISTINCT FROM
     ROW(OLD.public_id, OLD.customer_ref, OLD.customer_internal_id, OLD.customer_name_snapshot,
         OLD.currency, OLD.total_amount, OLD.item_count, OLD.recipient, OLD.address_line1, OLD.address_line2,
         OLD.city, OLD.region, OLD.postal_code, OLD.country_code, OLD.phone, OLD.created_at, OLD.created_by) THEN
    RAISE EXCEPTION 'order snapshots are immutable' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
